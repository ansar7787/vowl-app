import 'package:flutter/material.dart';
import 'package:flutter_screenutil/flutter_screenutil.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:vowl/features/reading/reading_conclusion/presentation/pages/reading_conclusion_practice_screen.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  Widget buildTestableWidget(Widget child) {
    return ScreenUtilInit(
      designSize: const Size(375, 812),
      builder: (context, _) => MaterialApp(
        home: child,
      ),
    );
  }

  group('ReadingConclusionPracticeScreen', () {
    testWidgets(
      'renders Next Step Predictor Gym, selects option, checks conclusion and reveals feedback',
      (tester) async {
        tester.view.physicalSize = const Size(375, 812);
        tester.view.devicePixelRatio = 1.0;
        addTearDown(tester.view.resetPhysicalSize);

        await tester.pumpWidget(
          buildTestableWidget(
            const ReadingConclusionPracticeScreen(level: 1),
          ),
        );
        await tester.pump();
        await tester.pump(const Duration(milliseconds: 300));

        expect(find.byType(ReadingConclusionPracticeScreen), findsOneWidget);
        expect(find.text('Next Step Predictor Gym'), findsOneWidget);
        expect(find.text('Check Conclusion'), findsOneWidget);

        // Select option A
        final optionAFinder = find.text('A');
        expect(optionAFinder, findsOneWidget);
        await tester.tap(optionAFinder);
        await tester.pumpAndSettle();

        // Tap Check Conclusion
        final checkFinder = find.text('Check Conclusion');
        await tester.ensureVisible(checkFinder);
        await tester.tap(checkFinder);
        await tester.pumpAndSettle();

        // Verify feedback appears
        expect(
          find.byWidgetPredicate(
            (w) =>
                w is Text &&
                (w.data == 'LOGIC CHAIN VERIFIED!' ||
                    w.data == 'LOGICAL FALLACY DETECTED'),
          ),
          findsOneWidget,
        );
      },
    );
  });
}
